#!/usr/bin/env python3
"""Gzip web/index.html (level 9, deterministic) into firmware/LED_Sign_Mesh/web_page.h.

Run from any directory:  python3 tools/build_web.py
The generated header is committed so the sketch builds from a clean clone.
"""
import gzip, hashlib, io, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "web" / "index.html"
OUT = ROOT / "firmware" / "LED_Sign_Mesh" / "web_page.h"
MAX_SRC = 40 * 1024


def main() -> int:
    if not SRC.exists():
        print(f"error: {SRC} not found", file=sys.stderr)
        return 1
    data = SRC.read_bytes()
    if len(data) > MAX_SRC:
        print(f"error: index.html is {len(data)} bytes (> {MAX_SRC})", file=sys.stderr)
        return 1
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", compresslevel=9, mtime=0) as g:
        g.write(data)
    gz = buf.getvalue()
    sha = hashlib.sha1(data).hexdigest()

    lines = []
    for i in range(0, len(gz), 16):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in gz[i:i + 16]) + ",")
    body = "\n".join(lines)
    rel = SRC.relative_to(ROOT).as_posix()
    header = f"""// web_page.h — GENERATED by tools/build_web.py, do not edit.
// Source: {rel} ({len(data)} bytes)
// Gzipped: {len(gz)} bytes (level 9, mtime 0)
// SHA1(source): {sha}
// Include from transport_web.cpp only (defines the array).
#ifndef WEB_PAGE_H
#define WEB_PAGE_H
#include <stdint.h>
#include <stddef.h>
#include <pgmspace.h>

const uint8_t WEB_INDEX_GZ[] PROGMEM = {{
{body}
}};
const size_t WEB_INDEX_GZ_LEN = {len(gz)};

#endif
"""
    OUT.write_text(header, newline="\n")
    print(f"{rel}: {len(data)} B -> {OUT.relative_to(ROOT).as_posix()}: {len(gz)} B gz, sha1 {sha[:12]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
