#!/usr/bin/env bash
# Build LED_Sign_Mesh and produce the distributable images (Phase 4: min_spiffs, OTA):
#   release/<git>/LED_Sign_HUB_install.bin    full 4 MB image, NVS pre-seeded role=HUB   (wired, flash at 0x0; wipes settings)
#   release/<git>/LED_Sign_NODE_install.bin   full 4 MB image, NVS pre-seeded role=NODE  (wired, flash at 0x0; wipes settings)
#   release/<git>/LED_Sign_ota.bin            the app image: upload to the hub (phone Settings -> Firmware,
#                                             or curl -F "file=@LED_Sign_ota.bin" http://192.168.4.1/ota),
#                                             then "Update all boards" pushes it to every node over the air
# The script owns the build: it writes firmware/LED_Sign_Mesh/build_id.h (BUILD_GIT = short hash, gitignored)
# BEFORE compiling, so the embedded git id always matches the images. Fails on any warning in our sources.
# Run from anywhere on the build box (Qwen box: ~/.local/bin/arduino-cli, core esp32 3.3.12).
set -euo pipefail
cd "$(dirname "$0")/.."
FQBN="esp32:esp32:lolin32:PartitionScheme=min_spiffs"
CLI=${ARDUINO_CLI:-$(command -v arduino-cli || echo ~/.local/bin/arduino-cli)}
SK=firmware/LED_Sign_Mesh
B=$SK/build/esp32.esp32.lolin32
VER=$(git rev-parse --short HEAD)
DIRTY=$(git status --porcelain -- firmware web | grep -q . && echo "-dirty" || true)
OUT=release/$VER
mkdir -p "$OUT"

printf '// GENERATED by tools/make_images.sh — do not commit (gitignored)\n#pragma once\n#define BUILD_GIT "%s%s"\n' "$VER" "$DIRTY" > "$SK/build_id.h"
echo "== build_id.h: BUILD_GIT \"$VER$DIRTY\""

echo "== compiling ($FQBN)"
"$CLI" compile --warnings all --fqbn "$FQBN" --export-binaries "$SK" > "$OUT/build.log" 2>&1 || { tail -30 "$OUT/build.log"; echo "!! compile failed"; exit 1; }
if grep -E "(LED_Sign_Mesh|/sketch)/[^ ]*: (warning|error):" "$OUT/build.log"; then echo "!! warnings in our sources (see $OUT/build.log)"; exit 1; fi
grep -E "Sketch uses|Global variables" "$OUT/build.log"

ESPTOOL=$(ls -d ~/.arduino15/packages/esp32/tools/esptool_py/*/esptool | head -1)
NVSGEN="python3 -m esp_idf_nvs_partition_gen.nvs_partition_gen"

make_nvs() {  # $1 = role value (0 node, 1 hub), $2 = out file
  printf 'key,type,encoding,value\nsys,namespace,,\nrole,data,u8,%s\n' "$1" > "$OUT/nvs_role$1.csv"
  $NVSGEN generate "$OUT/nvs_role$1.csv" "$2" 0x5000 >/dev/null
}
make_nvs 1 "$OUT/nvs_hub.bin"
make_nvs 0 "$OUT/nvs_node.bin"

# min_spiffs: nvs 0x9000/0x5000, otadata 0xE000 (boot_app0 = blank -> boots app0), app0 0x10000, app1 0x1F0000
merge() {  # $1 = nvs bin, $2 = out
  $ESPTOOL --chip esp32 merge-bin -o "$2" --flash-mode dio --flash-freq 80m --flash-size 4MB \
    0x1000 "$B/LED_Sign_Mesh.ino.bootloader.bin" 0x8000 "$B/LED_Sign_Mesh.ino.partitions.bin" \
    0x9000 "$1" 0xe000 "$B/boot_app0.bin" 0x10000 "$B/LED_Sign_Mesh.ino.bin" >/dev/null
}
merge "$OUT/nvs_hub.bin"  "$OUT/LED_Sign_HUB_install.bin"
merge "$OUT/nvs_node.bin" "$OUT/LED_Sign_NODE_install.bin"
cp "$B/LED_Sign_Mesh.ino.bin" "$OUT/LED_Sign_ota.bin"
rm -f "$OUT"/nvs_role*.csv "$OUT"/nvs_*.bin "$OUT"/LED_Sign_update_app.bin

cat > "$OUT/README.txt" <<EOF
LED_Sign_Mesh firmware $VER$DIRTY — built $(date -u +%Y-%m-%dT%H:%MZ) — $FQBN

Wired install ONCE per board (USB, erases saved settings: positions, message):
  LED_Sign_HUB_install.bin   -> the ONE hub board.   esptool --chip esp32 --port <port> --baud 115200 write-flash -z 0x0 LED_Sign_HUB_install.bin
  LED_Sign_NODE_install.bin  -> every other board.   esptool --chip esp32 --port <port> --baud 115200 write-flash -z 0x0 LED_Sign_NODE_install.bin

Every update after that is over the air (keeps role, positions, message):
  LED_Sign_ota.bin           -> phone: join the sign's Wi-Fi, Settings -> Firmware -> choose this file -> Upload to hub.
                                The hub reboots into it; then press "Update all boards" and the hub updates
                                every node, one at a time (~20 s each).
                                From a computer on the sign's Wi-Fi: curl -F "file=@LED_Sign_ota.bin" http://192.168.4.1/ota
                                then: curl -d '{"cmd":"ota_nodes"}' http://192.168.4.1/cmd
Rollback: a new image must run healthy for 30 s; if the board resets before that, it boots the previous image.
There is no wired "update" image any more (two app slots: an app-only write at 0x10000 would hit the wrong slot).
EOF
( cd "$OUT" && sha256sum *.bin > SHA256SUMS )
ls -la "$OUT"
